// jupPropClsEs is the class of the names lib/js-uprops.js answers, or nil for
// the rest. Twin of jupPropClsEs there.
func (st *rxSt) jupPropClsEs(name string) *rxCls {
	key, val, isPair := strings.Cut(name, "=")
	if !isPair {
		for i, n := range jupBinNames {
			if n == name {
				cls := rxNewCls()
				jxProps(cls, jupPBin+i/2)
				return cls
			}
		}
		return nil
	}
	if key != "Script_Extensions" && key != "scx" {
		return nil
	}
	// The script is named as for Script; its ordinal is the id jxScriptEs gives.
	sc := rxNewCls()
	if !jxScriptEs(sc, val) {
		st.fail("Invalid property name")
		return sc
	}
	cls := rxNewCls()
	jxProps(cls, jupPScx+sc.props[0]-rxPSc)
	return cls
}

// jupPropHit answers the ids above. Twin of jupPropHit in lib/js-uprops.js.
func jupPropHit(id, c int) bool {
	if c < 0 || c > 0x10FFFF {
		return false
	}
	if id >= jupPScx {
		k := jupScxSet(c)
		if k < 0 {
			return jxScript(c) == id-jupPScx
		}
		set := jupScxSets[k]
		for i := 0; i < len(set); i += 2 {
			if jcNum(set, i, 2) == id-jupPScx {
				return true
			}
		}
		return false
	}
	return jupBinHit(id-jupPBin, c)
}

// jupBinHit reports whether code point c has binary property b.
func jupBinHit(b, c int) bool {
	lo, z := jupBinAt[b], jupBinAt[b+1]
	a := lo
	for a < z {
		mid := (a + z) / 2
		if jcNum(jupBinTable, mid*4, 4) <= c {
			a = mid + 1
		} else {
			z = mid
		}
	}
	hit := (a-lo)%2 == 1
	if jupBinBase[b] < 0 {
		return hit
	}
	return hit != jupBinHit(jupBinBase[b], c)
}

// jupScxSet is the index in jupScxSets of c's Script_Extensions when they are
// not just its Script, else -1. Twin of jupScxSet in lib/js-uprops.js.
func jupScxSet(c int) int {
	t := jupScxTable
	a, z := 0, len(t)/10
	for a < z {
		mid := (a + z) / 2
		if jcNum(t, mid*10+4, 4) < c {
			a = mid + 1
		} else {
			z = mid
		}
	}
	if a*10 < len(t) && jcNum(t, a*10, 4) <= c {
		return jcNum(t, a*10+8, 2)
	}
	return -1
}

// jupFoldNext is the next member of c's case-fold orbit under JavaScript's i flag
// (mode 2 with u, 1 without), c itself when it is alone. Twin of jupFoldNext in
// lib/js-uprops.js.
func jupFoldNext(c rune, mode int) rune {
	if mode == 1 {
		if c > 0xFFFF {
			return c
		}
		if n := jupRingNext(jupFoldNTable, c); n >= 0 {
			return n
		}
	}
	x := jupRingNext(jupFoldUTable, c)
	if x < 0 {
		return c
	}
	for mode == 1 && x > 0xFFFF {
		x = jupRingNext(jupFoldUTable, x)
	}
	return x
}

func jupRingNext(t string, c rune) rune {
	a, z := 0, len(t)/8-1
	for a < z {
		mid := (a + z + 1) / 2
		if rune(jcNum(t, mid*8, 4)) <= c {
			a = mid
		} else {
			z = mid - 1
		}
	}
	if len(t) > 0 && rune(jcNum(t, a*8, 4)) == c {
		return rune(jcNum(t, a*8+4, 4))
	}
	return -1
}
