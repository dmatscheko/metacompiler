// Case mapping, the one implementation behind every engine's upper/lower: the
// MetaJS string methods toUpperCase / toLowerCase (here, builtin_method mids
// 27/28 in languages/lib/runtime.c, installGojaCaseMapping in commonscript.go)
// and the unicodeCase(s, mode) host function (host id 97 in runtime.c).
//
// mode is a bit set. Without caseFull it is the SIMPLE per-character mapping
// (UnicodeData.txt, Go's unicode.ToUpper / ToLower / ToTitle), which C# and Go
// specify. caseTitle maps every character to its titlecase (the capitalize
// methods apply it to one character), caseFold to its full case folding
// (CaseFolding.txt's C and F entries: "ß" -> "ss", "ς" -> "σ"; with caseFull
// "İ" -> "i̇"), Python's casefold and Ruby's casecmp?.
// caseFull adds SpecialCasing.txt's unconditional one-to-many mappings
// ("ß" -> "SS", "ﬁ" -> "FI", "İ" -> "i̇"), and caseSigma its Final_Sigma
// context: a capital sigma lowercases to "ς" when a cased letter precedes it
// and none follows (case-ignorable characters skipped both ways), as CPython's
// str.lower, ECMAScript's toLowerCase and Java's toLowerCase do. Ruby and Swift
// map fully without Final_Sigma. toUpperCase is caseUpper|caseFull and
// toLowerCase caseFull|caseSigma, ECMAScript's own definition.
//
// A lone surrogate (WTF-8, see strUnits in jsrt.go) has no case and passes
// through; it is neither cased nor case-ignorable.
const (
	caseUpper = 1
	caseFull  = 2
	caseSigma = 4
	caseTitle = 8
	caseFold  = 16
)

func caseMapMode(s string, mode int) string {
	up := mode&caseUpper != 0
	title := mode&caseTitle != 0
	if strASCII(s) {
		up = up || title
		b := []byte(s)
		for i, c := range b {
			if up && c >= 'a' && c <= 'z' {
				b[i] = c - 32
			} else if !up && c >= 'A' && c <= 'Z' {
				b[i] = c + 32
			}
		}
		return string(b)
	}
	var rs []rune
	for i := 0; i < len(s); {
		if c := wtf8Surrogate(s[i:]); c != 0 {
			rs = append(rs, c)
			i += 3
			continue
		}
		r, n := utf8.DecodeRuneInString(s[i:])
		rs = append(rs, r)
		i += n
	}
	var b strings.Builder
	var buf []byte
	for i, r := range rs {
		switch {
		case isSurrogate(r):
			buf = appendWTF8(buf[:0], r)
			b.Write(buf)
		case mode&caseFold != 0 && caseFoldFull[r] != "":
			b.WriteString(caseFoldFull[r])
		case title && mode&caseFull != 0 && caseTitleFull[r] != "":
			b.WriteString(caseTitleFull[r])
		case title:
			b.WriteRune(unicode.ToTitle(r))
		case up && mode&caseFull != 0 && caseUpperFull[r] != "":
			b.WriteString(caseUpperFull[r])
		case up:
			b.WriteRune(unicode.ToUpper(r))
		case r == 0x130 && mode&caseFull != 0:
			b.WriteString("i̇")
		case r == 0x3A3 && mode&caseSigma != 0 && caseFinalSigma(rs, i):
			b.WriteRune(0x3C2)
		default:
			b.WriteRune(unicode.ToLower(r))
		}
	}
	return b.String()
}

// caseFinalSigma: the Σ at rs[i] ends a word - a cased letter precedes it and
// none follows, case-ignorable characters skipped both ways. Twin of
// case_final_sigma in languages/lib/runtime.c.
func caseFinalSigma(rs []rune, i int) bool {
	j := i - 1
	for j >= 0 && caseIn(caseIgnorableR, rs[j]) {
		j--
	}
	if j < 0 || !caseIn(caseCasedR, rs[j]) {
		return false
	}
	j = i + 1
	for j < len(rs) && caseIn(caseIgnorableR, rs[j]) {
		j++
	}
	return j == len(rs) || !caseIn(caseCasedR, rs[j])
}

// caseIn: r lies in one of the [lo, hi] pairs of a sorted range list.
func caseIn(t []int32, r rune) bool {
	lo, hi := 0, len(t)/2-1
	for lo <= hi {
		m := (lo + hi) / 2
		switch {
		case r < t[2*m]:
			hi = m - 1
		case r > t[2*m+1]:
			lo = m + 1
		default:
			return true
		}
	}
	return false
}

