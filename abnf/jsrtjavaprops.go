package abnf

import "strings"

// java.util.regex's \p{..} properties for the shared engine's J dialect: the
// Go twin of the names and tables in languages/lib/java-regex.js (that file
// describes the encoding), over java.lang.Character's own classification in
// jsrtjavachars.go.

// jxCharPreds and jxCharIs are java.lang.Character's predicates past the
// ones jvCharMembers spells out; twins of JX_CHAR_PREDS and jxCharIs in
// lib/java-regex.js, which describe them.
var jxCharPreds = []string{"isIdeographic", "isMirrored", "isEmoji", "isEmojiPresentation", "isEmojiModifier",
	"isEmojiModifierBase", "isEmojiComponent", "isExtendedPictographic", "isSpaceChar", "isISOControl",
	"isTitleCase", "isDefined", "isJavaIdentifierStart", "isJavaLetter", "isJavaIdentifierPart",
	"isJavaLetterOrDigit", "isUnicodeIdentifierStart", "isUnicodeIdentifierPart", "isIdentifierIgnorable",
	"isSurrogate", "isHighSurrogate", "isLowSurrogate", "isSupplementaryCodePoint", "isValidCodePoint",
	"isBmpCodePoint", "isSpace"}

func jxCharIs(name string, c int) bool {
	for k := 0; k < 8; k++ {
		if jxCharPreds[k] == name {
			return rxPropHit(rxPBin+k, rune(c))
		}
	}
	switch name {
	case "isSpaceChar":
		g := jxGc(c)
		return g >= 12 && g <= 14
	case "isISOControl":
		return (c >= 0 && c <= 31) || (c >= 127 && c <= 159)
	case "isTitleCase":
		return jxGc(c) == 3
	case "isDefined":
		return jxGc(c) != 0
	case "isJavaIdentifierStart", "isJavaLetter":
		return rxPropHit(rxPJStart, rune(c))
	case "isJavaIdentifierPart", "isJavaLetterOrDigit":
		return rxPropHit(rxPJPart, rune(c))
	case "isUnicodeIdentifierStart":
		return rxPropHit(rxPUStart, rune(c))
	case "isUnicodeIdentifierPart":
		return rxPropHit(rxPUPart, rune(c))
	case "isIdentifierIgnorable":
		return rxPropHit(rxPIgnore, rune(c))
	case "isSurrogate":
		return c >= 0xD800 && c <= 0xDFFF
	case "isHighSurrogate":
		return c >= 0xD800 && c <= 0xDBFF
	case "isLowSurrogate":
		return c >= 0xDC00 && c <= 0xDFFF
	case "isSupplementaryCodePoint":
		return c >= 0x10000 && c <= 0x10FFFF
	case "isValidCodePoint":
		return c >= 0 && c <= 0x10FFFF
	case "isBmpCodePoint":
		return c >= 0 && c <= 0xFFFF
	}
	return c == 9 || c == 10 || c == 12 || c == 13 || c == 32
}

// rxPropHit answers whether c has the \p{..} property id (rxP* in
// jsrtregex.go). Twin of jxPropHit in lib/java-regex.js.
func rxPropHit(id int, ch rune) bool {
	c := int(ch)
	switch {
	case id >= rxPBlk:
		return jxBlock(c) == id-rxPBlk
	case id >= rxPSc:
		return jxScript(c) == id-rxPSc
	case id >= rxPGc:
		return jxGc(c) == id-rxPGc
	case id >= rxPBin:
		return jxBin(c)>>(id-rxPBin)&1 == 1
	}
	switch id {
	case rxPL:
		return jcIsLetter(c)
	case rxPND:
		return jcIsDigit(c)
	case rxPAlpha:
		return jcIsAlphabetic(c)
	case rxPUpper:
		return jcIsUpper(c)
	case rxPLower:
		return jcIsLower(c)
	case rxPLD:
		return jcIsLetter(c) || jcIsDigit(c)
	case rxPJoin:
		return c == 0x200C || c == 0x200D
	case rxPNonCh:
		return c&0xFFFE == 0xFFFE || (c >= 0xFDD0 && c <= 0xFDEF)
	case rxPHex:
		return jcIsDigit(c) || rxIsHex(ch) || (c >= 0xFF10 && c <= 0xFF19) || (c >= 0xFF21 && c <= 0xFF26) ||
			(c >= 0xFF41 && c <= 0xFF46)
	case rxPIgnore:
		return c <= 8 || (c >= 14 && c <= 27) || (c >= 127 && c <= 159) || jxGc(c) == 16
	}
	g := jxGc(c)
	sep := g >= 12 && g <= 14
	graph := !sep && g != 15 && g != 19 && g != 0
	start := jcIsLetter(c) || g == 10
	part := start || g == 9 || g == 6 || g == 8 || rxPropHit(rxPIgnore, ch)
	switch id {
	case rxPLu:
		return g == 1
	case rxPLl:
		return g == 2
	case rxPLt:
		return g == 3
	case rxPNl:
		return g == 10
	case rxPCased:
		return g == 3 || jcIsUpper(c) || jcIsLower(c)
	case rxPAssigned:
		return g != 0
	case rxPAlnum:
		return jcIsAlphabetic(c) || g == 9
	case rxPWord:
		return jcIsAlphabetic(c) || (g >= 6 && g <= 9) || g == 23 || c == 0x200C || c == 0x200D
	case rxPWhite:
		return sep || (c >= 9 && c <= 13) || c == 0x85
	case rxPBlank:
		return g == 12 || c == 9
	case rxPJWhite:
		return (sep && c != 0xA0 && c != 0x2007 && c != 0x202F) || (c >= 9 && c <= 13) || (c >= 0x1C && c <= 0x1F)
	case rxPGraph:
		return graph
	case rxPPrint:
		return (graph || g == 12 || c == 9) && g != 15
	case rxPUStart:
		return start || jxIdExtra(c) == 1
	case rxPUPart:
		return part || g == 23 || jxIdExtra(c) > 0
	case rxPJStart:
		return start || g == 26 || g == 23
	case rxPJPart:
		return start || g == 26 || g == 23 || part
	}
	return false
}

// jxIdExtra: 1 for Other_ID_Start, 2 for the Other_ID_Continue characters no
// general category covers. Twin of jxIdExtra in lib/java-regex.js.
func jxIdExtra(c int) int {
	switch {
	case c == 0x1885 || c == 0x1886 || c == 0x2118 || c == 0x212E || c == 0x309B || c == 0x309C:
		return 1
	case c == 0xB7 || c == 0x387 || (c >= 0x1369 && c <= 0x1371) || c == 0x19DA || c == 0x30FB || c == 0xFF65:
		return 2
	}
	return 0
}

// jxGc, jxScript, jxBlock and jxBin read the tables below; twins of the
// functions of the same names in lib/java-regex.js.
func jxGc(c int) int {
	if c < 0 || c > 0x10FFFF {
		return 0
	}
	return jcDig(jxGcTable, jcRun(jxGcTable, c, 5)*5+4)
}

func jxScript(c int) int {
	if c < 0 || c > 0x10FFFF {
		return -1
	}
	return jcNum(jxScTable, jcRun(jxScTable, c, 6)*6+4, 2)
}

func jxBlock(c int) int {
	if c < 0 || c > 0x10FFFF {
		return 0
	}
	return jcNum(jxBlkTable, jcRun(jxBlkTable, c, 6)*6+4, 2)
}

func jxBin(c int) int {
	if c < 0 || c > 0x10FFFF {
		return 0
	}
	return jcNum(jxBinTable, jcRun(jxBinTable, c, 6)*6+4, 2)
}

// jxGraphNext is Grapheme.nextBoundary: the end of the extended grapheme
// cluster that starts at off. Twin of jxGraphNext in lib/java-regex.js, which
// describes jxGbTable. An off at or past limit is its own boundary.
func jxGraphNext(text []rune, off, limit int) int {
	if off >= limit {
		return off
	}
	c0, w0 := rxCpAt(text, off)
	g0 := jxGb(c0)
	t0 := g0 % 16
	ret := off + w0
	ri := 0
	if t0 == 6 {
		ri = 1
	}
	gb11 := t0 == 14
	for ret < limit {
		c1, w1 := rxCpAt(text, ret)
		g1 := jxGb(c1)
		t1 := g1 % 16
		// GB9c, without moving Java's notion of the previous character.
		if g0/16 == 2 {
			if adv := jxIncb(text, ret, limit); adv >= 0 {
				ret += adv
				continue
			}
		}
		switch {
		case gb11 && t0 == 5 && t1 == 14: // GB11
		case ri%2 == 1 && t0 == 6 && t1 == 6: // GB12, GB13
		case jxGbBreak(t0, t1):
			return ret
		}
		if t1 == 6 {
			ri++
		}
		g0, t0 = g1, t1
		ret += w1
	}
	return ret
}

// jxGbBreak is Grapheme's rules table; twin of jxGbBreak in lib/java-regex.js.
func jxGbBreak(t0, t1 int) bool {
	switch {
	case t0 == 1 && t1 == 2:
		return false
	case (t0 >= 1 && t0 <= 3) || (t1 >= 1 && t1 <= 3):
		return true
	case t0 == 9 && (t1 == 9 || t1 == 10 || t1 == 12 || t1 == 13):
		return false
	case (t0 == 12 || t0 == 10) && (t1 == 10 || t1 == 11):
		return false
	case (t0 == 13 || t0 == 11) && t1 == 11:
		return false
	}
	return !(t1 == 4 || t1 == 5 || t1 == 8 || t0 == 7)
}

// jxIncb is Grapheme.checkIndicConjunctBreak; twin of jxIncb in
// lib/java-regex.js.
func jxIncb(text []rune, index, limit int) int {
	linker := false
	for adv := 0; index+adv < limit; {
		c, w := rxCpAt(text, index+adv)
		k := jxGb(c) / 16
		adv += w
		switch {
		case k == 1:
			linker = true
		case k == 2 && linker:
			return adv
		case k != 3:
			return -1
		}
	}
	return -1
}

func jxGb(c rune) int {
	return jcDig(jxGbTable, jcRun(jxGbTable, int(c), 5)*5+4)
}

// propCls is Pattern.family's reading of \p{name}; twin of jxPropCls in
// lib/java-regex.js.
func (st *rxSt) propCls(name string, at int) *rxCls {
	cls := rxNewCls()
	ok := false
	if eq := strings.Index(name, "="); eq >= 0 {
		key, val := strings.ToLower(name[:eq]), name[eq+1:]
		switch key {
		case "sc", "script":
			ok = jxScriptCls(cls, val)
		case "blk", "block":
			ok = jxBlockCls(cls, val)
		case "gc", "general_category":
			ok = st.forProperty(cls, val)
		}
		if !ok {
			st.failAt("Unknown Unicode property {name=<"+key+">, value=<"+val+">}", at)
		}
		return cls
	}
	switch {
	case strings.HasPrefix(name, "In"):
		ok = jxBlockCls(cls, name[2:])
	case strings.HasPrefix(name, "Is"):
		sh := name[2:]
		ok = st.unicodeProp(cls, strings.ToUpper(sh)) || st.forProperty(cls, sh) || jxScriptCls(cls, sh)
	default:
		if st.uclass {
			ok = st.posixU(cls, strings.ToUpper(name))
		}
		if !ok {
			ok = st.forProperty(cls, name)
		}
	}
	if !ok {
		st.failAt("Unknown character property name {"+name+"}", at)
	}
	return cls
}

// jxProps adds property ids to cls; jxGcs the general categories whose names
// start with prefix.
func jxProps(cls *rxCls, ids ...int) bool {
	cls.props = append(cls.props, ids...)
	cls.x = true
	return true
}

const jxGcNames = "Cn Lu Ll Lt Lm Lo Mn Me Mc Nd Nl No Zs Zl Zp Cc Cf -- Co Cs Pd Ps Pe Pc Po Sm Sc Sk So Pi Pf "

func jxGcs(cls *rxCls, prefix string) bool {
	for t := 0; t < 31; t++ {
		if strings.HasPrefix(jxGcNames[3*t:], prefix) {
			jxProps(cls, rxPGc+t)
		}
	}
	return true
}

// cased is the id of a case property, or rxPCased under CASE_INSENSITIVE.
func (st *rxSt) cased(id int) int {
	if st.icase {
		return rxPCased
	}
	return id
}

// unicodeProp is CharPredicates.forUnicodeProperty; twin of jxUnicodeProp.
func (st *rxSt) unicodeProp(cls *rxCls, u string) bool {
	switch u {
	case "ALPHABETIC":
		return jxProps(cls, rxPAlpha)
	case "ASSIGNED":
		return jxProps(cls, rxPAssigned)
	case "CONTROL":
		return jxGcs(cls, "Cc")
	case "EMOJI":
		return jxProps(cls, rxPBin+2)
	case "EMOJI_PRESENTATION":
		return jxProps(cls, rxPBin+3)
	case "EMOJI_MODIFIER":
		return jxProps(cls, rxPBin+4)
	case "EMOJI_MODIFIER_BASE":
		return jxProps(cls, rxPBin+5)
	case "EMOJI_COMPONENT":
		return jxProps(cls, rxPBin+6)
	case "EXTENDED_PICTOGRAPHIC":
		return jxProps(cls, rxPBin+7)
	case "HEXDIGIT", "HEX_DIGIT":
		return jxProps(cls, rxPHex)
	case "IDEOGRAPHIC":
		return jxProps(cls, rxPBin)
	case "JOINCONTROL", "JOIN_CONTROL":
		return jxProps(cls, rxPJoin)
	case "LETTER":
		return jxProps(cls, rxPL)
	case "LOWERCASE":
		// PCRE2 (C) keeps its binary Lowercase and Uppercase caseful.
		if st.pcre {
			return jxProps(cls, rxPLower)
		}
		return jxProps(cls, st.cased(rxPLower))
	case "NONCHARACTERCODEPOINT", "NONCHARACTER_CODE_POINT":
		return jxProps(cls, rxPNonCh)
	case "TITLECASE":
		return jxProps(cls, st.cased(rxPLt))
	case "PUNCTUATION":
		return jxGcs(cls, "P")
	case "UPPERCASE":
		if st.pcre {
			return jxProps(cls, rxPUpper)
		}
		return jxProps(cls, st.cased(rxPUpper))
	case "WHITESPACE", "WHITE_SPACE":
		return jxProps(cls, rxPWhite)
	case "WORD":
		return jxProps(cls, rxPWord)
	}
	return st.posixU(cls, u)
}

// posixU is CharPredicates.getPosixPredicate; twin of jxPosixU.
func (st *rxSt) posixU(cls *rxCls, u string) bool {
	switch u {
	case "ALPHA":
		return jxProps(cls, rxPAlpha)
	case "LOWER":
		return jxProps(cls, st.cased(rxPLower))
	case "UPPER":
		return jxProps(cls, st.cased(rxPUpper))
	case "SPACE":
		return jxProps(cls, rxPWhite)
	case "PUNCT":
		return jxGcs(cls, "P")
	case "XDIGIT":
		return jxProps(cls, rxPHex)
	case "ALNUM":
		return jxProps(cls, rxPAlnum)
	case "CNTRL":
		return jxGcs(cls, "Cc")
	case "DIGIT":
		return jxProps(cls, rxPND)
	case "BLANK":
		return jxProps(cls, rxPBlank)
	case "GRAPH":
		return jxProps(cls, rxPGraph)
	case "PRINT":
		return jxProps(cls, rxPPrint)
	}
	return false
}

// forProperty is CharPredicates.forProperty; twin of jxForProperty.
func (st *rxSt) forProperty(cls *rxCls, name string) bool {
	switch {
	case name == "LC" || (st.icase && !st.pcre && (name == "Lu" || name == "Ll" || name == "Lt")):
		return jxProps(cls, rxPGc+1, rxPGc+2, rxPGc+3)
	case name == "LD":
		return jxGcs(cls, "L") && jxGcs(cls, "Nd")
	case len(name) == 2 && name != "--" && strings.Contains(jxGcNames, name+" "):
		return jxGcs(cls, name)
	case len(name) == 1 && strings.Contains("LMNZCPS", name):
		return jxGcs(cls, name)
	}
	posix := map[string]string{"ASCII": "ascii", "Alnum": "alnum", "Alpha": "alpha", "Blank": "blank",
		"Cntrl": "cntrl", "Digit": "digit", "Graph": "graph", "Lower": "lower", "Print": "print",
		"Punct": "punct", "Space": "space", "Upper": "upper", "XDigit": "xdigit"}
	if pn, ok := posix[name]; ok {
		if st.icase && (pn == "lower" || pn == "upper") {
			pn = "alpha"
		}
		return rxPosixAdd(cls, pn)
	}
	switch name {
	case "L1":
		cls.add(0, 255)
		return true
	case "all":
		cls.add(0, 0x10FFFF)
		return true
	case "javaLowerCase":
		return jxProps(cls, st.cased(rxPLower))
	case "javaUpperCase":
		return jxProps(cls, st.cased(rxPUpper))
	case "javaTitleCase":
		return jxProps(cls, st.cased(rxPLt))
	case "javaAlphabetic":
		return jxProps(cls, rxPAlpha)
	case "javaIdeographic":
		return jxProps(cls, rxPBin)
	case "javaDigit":
		return jxProps(cls, rxPND)
	case "javaDefined":
		return jxProps(cls, rxPAssigned)
	case "javaLetter":
		return jxProps(cls, rxPL)
	case "javaLetterOrDigit":
		return jxProps(cls, rxPLD)
	case "javaJavaIdentifierStart":
		return jxProps(cls, rxPJStart)
	case "javaJavaIdentifierPart":
		return jxProps(cls, rxPJPart)
	case "javaUnicodeIdentifierStart":
		return jxProps(cls, rxPUStart)
	case "javaUnicodeIdentifierPart":
		return jxProps(cls, rxPUPart)
	case "javaIdentifierIgnorable":
		return jxProps(cls, rxPIgnore)
	case "javaSpaceChar":
		return jxGcs(cls, "Z")
	case "javaWhitespace":
		return jxProps(cls, rxPJWhite)
	case "javaMirrored":
		return jxProps(cls, rxPBin+1)
	case "javaISOControl":
		cls.add(0, 31)
		cls.add(127, 159)
		return true
	}
	return false
}

// jxScriptCls is Character.UnicodeScript.forName over jxScNameTable; twin of
// jxScriptCls in lib/java-regex.js.
func jxScriptCls(cls *rxCls, name string) bool {
	u := strings.ToUpper(name)
	if u == "" || strings.ContainsAny(u, " ;") {
		return false
	}
	if k := strings.Index(jxScNameTable, ";"+u+" "); k >= 0 {
		return jxProps(cls, rxPSc+strings.Count(jxScNameTable[:k], ";"))
	}
	if k := strings.Index(jxScNameTable, " "+u+";"); k >= 0 {
		return jxProps(cls, rxPSc+strings.Count(jxScNameTable[:k], ";")-1)
	}
	return false
}

// jxBlockCls is Character.UnicodeBlock.forName over jxBlkNameTable; twin of
// jxBlockCls in lib/java-regex.js.
func jxBlockCls(cls *rxCls, name string) bool {
	u := strings.ToUpper(name)
	if u == "" || strings.ContainsAny(u, ";/") {
		return false
	}
	for n, rec := range strings.Split(strings.Trim(jxBlkNameTable, ";"), ";") {
		keys := strings.Split(rec, "/")
		if keys[0] == u {
			return jxProps(cls, rxPBlk+n+1)
		}
		for _, k := range keys[1:] {
			if k == "*" {
				k = strings.ReplaceAll(keys[0], "_", " ")
			}
			if k == u || strings.ReplaceAll(k, " ", "") == u {
				return jxProps(cls, rxPBlk+n+1)
			}
		}
	}
	return false
}

