function jcDig(t, i) {
    var c = t.charCodeAt(i)
    if (c <= 91) { return c - 48 }
    return c - 49
}
// The number in the n digits at position i.
function jcNum(t, i, n) {
    var v = 0
    var k = 0
    while (k < n) {
        v = v * 64 + jcDig(t, i + k)
        k = k + 1
    }
    return v
}
// The index of the run of w-digit records that holds code point c
// (0 <= c <= U+10FFFF).
function jcRun(t, c, w) {
    var lo = 0
    var hi = t.length / w - 1
    while (lo < hi) {
        var mid = Math.floor((lo + hi + 1) / 2)
        if (jcNum(t, mid * w, 4) <= c) { lo = mid } else { hi = mid - 1 }
    }
    return lo
}
// The class of code point c; 0 for anything outside U+0000..U+10FFFF.
function jcClass(c) {
    if (c < 0 || c > 1114111) { return 0 }
    var t = jcTab()
    return jcDig(t, jcRun(t, c, 5) * 5 + 4)
}
function jcIsLetter(c) {
    if (c < 128) { return (c >= 65 && c <= 90) || (c >= 97 && c <= 122) }
    var k = jcClass(c) % 8
    return k >= 1 && k <= 4
}
function jcIsDigit(c) {
    if (c < 128) { return c >= 48 && c <= 57 }
    return jcClass(c) % 8 == 5
}
function jcIsAlphabetic(c) {
    if (c < 128) { return (c >= 65 && c <= 90) || (c >= 97 && c <= 122) }
    var k = jcClass(c)
    return (k % 8 >= 1 && k % 8 <= 4) || k % 8 == 6 || Math.floor(k / 8) % 2 == 1
}
function jcIsUpper(c) {
    if (c < 128) { return c >= 65 && c <= 90 }
    var k = jcClass(c)
    return k % 8 == 1 || Math.floor(k / 16) % 2 == 1
}
function jcIsLower(c) {
    if (c < 128) { return c >= 97 && c <= 122 }
    var k = jcClass(c)
    return k % 8 == 2 || Math.floor(k / 32) % 2 == 1
}
// Character.digit's value of c in radix 36: a decimal digit of any script,
// then the Latin letters in both their ASCII and their fullwidth forms as
// 10..35; 99 for anything else.
function jcDigitVal(c) {
    if (c >= 48 && c <= 57) { return c - 48 }
    if (c >= 97 && c <= 122) { return c - 87 }
    if (c >= 65 && c <= 90) { return c - 55 }
    if (c >= 65345 && c <= 65370) { return c - 65335 }
    if (c >= 65313 && c <= 65338) { return c - 65303 }
    if (c < 128 || c > 1114111) { return 99 }
    var t = jcTab()
    var r = jcRun(t, c, 5)
    if (jcDig(t, r * 5 + 4) != 5) { return 99 }
    return (c - jcNum(t, r * 5, 4)) % 10
}

