// Character.getNumericValue: Character.digit's value, else the second table's.
function jcNumericValue(c) {
    var d = jcDigitVal(c)
    if (d != 99) { return d }
    if (c < 0 || c > 1114111) { return 0 - 1 }
    var t = jcNumTab()
    var r = jcRun(t, c, 10)
    var base = jcNum(t, r * 10 + 4, 5) - 2
    if (base < 0) { return base }
    return base + (c - jcNum(t, r * 10, 4)) * jcDig(t, r * 10 + 9)
}
